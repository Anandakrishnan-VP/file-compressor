export function pickScene(file) {
  if (!file) return CHAMBERS.BlackHole;

  // Check size thresholds
  if (file.size > 50 * 1024 * 1024) {
    return CHAMBERS.Volcano;
  }
  if (file.size > 0 && file.size < 50) {
    return CHAMBERS.Tweezers;
  }

  const nameParts = file.name.split('.');
  if (nameParts.length < 2) {
    return CHAMBERS.BlackHole;
  }
  const ext = nameParts.pop().toLowerCase();
  const chamberKey = EXTENSION_MAP[ext];
  return CHAMBERS[chamberKey] || CHAMBERS.BlackHole;
}

export function getRandomChamber() {
  const keys = Object.keys(CHAMBERS);
  const randomKey = keys[Math.floor(Math.random() * keys.length)];
  return CHAMBERS[randomKey];
}
